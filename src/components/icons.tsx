interface IconProps extends LucideProps {
  name: IconKey;
}

/** All icons are decorative by default (aria-hidden). Pair with visible text. */
export function Icon({ name, size = 20, strokeWidth = 1.75, ...rest }: IconProps) {
  const Component = map[name];
  return <Component size={size} strokeWidth={strokeWidth} aria-hidden="true" focusable="false" {...rest} />;
}

